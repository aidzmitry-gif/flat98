def sched(x,y,widths,heads,rows,row=12):
    total=sum(widths);rect(x,y-8,total,8,green,green)
    for j,h in enumerate(heads):text(x+sum(widths[:j])+1.6,y-5.4,h,2.95,True,'#ffffff')
    y-=8
    for i,r in enumerate(rows):
        rect(x,y-row,total,row,'#f6f6f1' if i%2==0 else '#ffffff','#d9dfd9')
        for j,s in enumerate(r):
            xx=x+sum(widths[:j])+1.6
            words=[];lines=[]
            for word in str(s).split():
                if words and pdfmetrics.stringWidth(' '.join(words+[word]),'ui',3)>widths[j]-3.4:lines.append(' '.join(words));words=[]
                words.append(word)
            if words:lines.append(' '.join(words))
            assert len(lines)*3.8<=row,(s,row)
            for k,l in enumerate(lines):text(xx,y-4.5-k*3.8,l,3)
        y-=row
    return y
